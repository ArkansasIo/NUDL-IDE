// C# Generator
// -------------------------------------------------------------
function generateCSharp(program: Program): string {
  let out = '// Generated by NUDL 0.3 C# Backend\nusing System;\nusing System.Collections.Generic;\n\npublic class Program {\n';

  for (const f of program.functions) {
    const isMain = f.name === 'main';
    const retType = isMain ? 'static int' : `public static ${mapCppType(f.returnType)}`;
    const params = isMain && f.params.length === 0 ? '' : f.params.map((p) => `${mapCppType(p.type)} ${p.name}`).join(', ');
    out += `    ${retType} ${isMain ? 'Main' : f.name}(${params}) {\n`;
    for (const stmt of f.body) {
      out += emitCSharpStmt(stmt, 2);
    }
    if (isMain && !f.body.some((s) => s.type === 'Return')) {
      out += `        return 0;\n`;
    }
    out += `    }\n\n`;
  }

  if (!program.functions.some((f) => f.name === 'main')) {
    out += `    public static int Main() {\n`;
    for (const stmt of program.statements) {
      out += emitCSharpStmt(stmt, 2);
    }
    out += `        return 0;\n    }\n`;
  }

  out += `}\n`;
  return out;
}

function emitCSharpStmt(stmt: Stmt, indent: number): string {
  const pad = '    '.repeat(indent);
  switch (stmt.type) {
    case 'Binding':
      return `${pad}var ${stmt.name} = ${exprToString(stmt.value)};\n`;
    case 'Assign':
      return `${pad}${stmt.target} = ${exprToString(stmt.value)};\n`;
    case 'Return':
      return `${pad}return ${exprToString(stmt.value)};\n`;
    case 'ExprStmt': {
      if (stmt.value.type === 'Call' && stmt.value.callee === 'print') {
        const args = stmt.value.args.map(exprToString).join(' + " " + ');
        return `${pad}Console.WriteLine(${args});\n`;
      }
      return `${pad}${exprToString(stmt.value)};\n`;
    }
    default:
      return '';
  }
}

