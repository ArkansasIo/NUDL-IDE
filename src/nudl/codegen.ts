// C (C99) Generator
// -------------------------------------------------------------
function generateC(program: Program): string {
  let out = '// Generated by NUDL 0.3 C Backend\n#include <stdio.h>\n#include <stdbool.h>\n#include <string.h>\n\n';

  for (const f of program.functions) {
    const isMain = f.name === 'main';
    const retType = isMain ? 'int' : mapCType(f.returnType);
    const params = f.params.length === 0 ? 'void' : f.params.map((p) => `${mapCType(p.type)} ${p.name}`).join(', ');
    out += `${retType} ${f.name}(${params}) {\n`;
    for (const stmt of f.body) {
      out += emitCStmt(stmt, 1);
    }
    if (isMain && !f.body.some((s) => s.type === 'Return')) {
      out += `    return 0;\n`;
    }
    out += `}\n\n`;
  }

  if (!program.functions.some((f) => f.name === 'main')) {
    out += `int main(void) {\n`;
    for (const stmt of program.statements) {
      out += emitCStmt(stmt, 1);
    }
    out += `    return 0;\n}\n`;
  }

  return out;
}

function mapCType(t: string): string {
  switch (t) {
    case 'i64':
    case 'int':
      return 'long long';
    case 'f64':
    case 'float':
      return 'double';
    case 'bool':
      return 'bool';
    case 'string':
    case 'text':
      return 'const char*';
    default:
      return 'long long';
  }
}

function emitCStmt(stmt: Stmt, indent: number): string {
  const pad = '    '.repeat(indent);
  switch (stmt.type) {
    case 'Binding':
      return `${pad}${mapCType(stmt.varType || 'i64')} ${stmt.name} = ${exprToString(stmt.value)};\n`;
    case 'Assign':
      return `${pad}${stmt.target} = ${exprToString(stmt.value)};\n`;
    case 'Return':
      return `${pad}return ${exprToString(stmt.value)};\n`;
    case 'ExprStmt': {
      if (stmt.value.type === 'Call' && stmt.value.callee === 'print') {
        const arg = stmt.value.args[0] ? exprToString(stmt.value.args[0]) : '""';
        return `${pad}printf("%s\\n", ${arg});\n`;
      }
      return `${pad}${exprToString(stmt.value)};\n`;
    }
    case 'If': {
      let res = `${pad}if (${exprToString(stmt.condition)}) {\n`;
      for (const s of stmt.thenBranch) res += emitCStmt(s, indent + 1);
      res += `${pad}}`;
      if (stmt.elseBranch) {
        res += ` else {\n`;
        for (const s of stmt.elseBranch) res += emitCStmt(s, indent + 1);
        res += `${pad}}`;
      }
      return res + '\n';
    }
    case 'While': {
      let res = `${pad}while (${exprToString(stmt.condition)}) {\n`;
      for (const s of stmt.body) res += emitCStmt(s, indent + 1);
      res += `${pad}}\n`;
      return res;
    }
    default:
      return '';
  }
}

