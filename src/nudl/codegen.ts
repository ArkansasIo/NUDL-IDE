// Java Generator
// -------------------------------------------------------------
function generateJava(program: Program): string {
  let out = '// Generated by NUDL 0.3 Java Backend\npublic class Main {\n';

  for (const f of program.functions) {
    if (f.name === 'main') {
      out += `    public static void main(String[] args) {\n`;
      for (const stmt of f.body) {
        out += emitJavaStmt(stmt, 2);
      }
      out += `    }\n\n`;
    } else {
      out += `    public static ${mapCType(f.returnType)} ${f.name}() {\n`;
      for (const stmt of f.body) {
        out += emitJavaStmt(stmt, 2);
      }
      out += `    }\n\n`;
    }
  }

  if (!program.functions.some((f) => f.name === 'main')) {
    out += `    public static void main(String[] args) {\n`;
    for (const stmt of program.statements) {
      out += emitJavaStmt(stmt, 2);
    }
    out += `    }\n`;
  }

  out += `}\n`;
  return out;
}

function emitJavaStmt(stmt: Stmt, indent: number): string {
  const pad = '    '.repeat(indent);
  switch (stmt.type) {
    case 'Binding':
      return `${pad}var ${stmt.name} = ${exprToString(stmt.value)};\n`;
    case 'ExprStmt': {
      if (stmt.value.type === 'Call' && stmt.value.callee === 'print') {
        const args = stmt.value.args.map(exprToString).join(' + " " + ');
        return `${pad}System.out.println(${args});\n`;
      }
      return `${pad}${exprToString(stmt.value)};\n`;
    }
    case 'Return':
      return `${pad}return ${exprToString(stmt.value)};\n`;
    default:
      return '';
  }
}

