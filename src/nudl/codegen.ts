// Rust Generator
// -------------------------------------------------------------
function generateRust(program: Program): string {
  let out = '// Generated by NUDL 0.3 Rust Backend\n\n';

  for (const s of program.structs) {
    out += `#[derive(Debug, Clone)]\npub struct ${s.name} {\n`;
    for (const f of s.fields) {
      out += `    pub ${f.name}: ${mapRustType(f.type)},\n`;
    }
    out += `}\n\n`;
  }

  for (const f of program.functions) {
    const isMain = f.name === 'main';
    const retType = isMain ? '' : ` -> ${mapRustType(f.returnType)}`;
    const params = f.params.map((p) => `${p.name}: ${mapRustType(p.type)}`).join(', ');
    out += `fn ${f.name}(${params})${retType} {\n`;
    for (const stmt of f.body) {
      out += emitRustStmt(stmt, 1);
    }
    out += `}\n\n`;
  }

  if (!program.functions.some((f) => f.name === 'main')) {
    out += `fn main() {\n`;
    for (const stmt of program.statements) {
      out += emitRustStmt(stmt, 1);
    }
    out += `}\n`;
  }

  return out;
}

function mapRustType(t: string): string {
  switch (t) {
    case 'i64':
    case 'int':
      return 'i64';
    case 'f64':
    case 'float':
      return 'f64';
    case 'bool':
      return 'bool';
    case 'string':
    case 'text':
      return 'String';
    case 'void':
      return '()';
    default:
      if (t.endsWith('[]')) return `Vec<${mapRustType(t.slice(0, -2))}>`;
      return t || 'i64';
  }
}

function emitRustStmt(stmt: Stmt, indent: number): string {
  const pad = '    '.repeat(indent);
  switch (stmt.type) {
    case 'Binding':
      return `${pad}let ${stmt.constant ? '' : 'mut '}${stmt.name} = ${exprToString(stmt.value)};\n`;
    case 'Assign':
      return `${pad}${stmt.target} = ${exprToString(stmt.value)};\n`;
    case 'Return':
      return `${pad}return ${exprToString(stmt.value)};\n`;
    case 'ExprStmt': {
      if (stmt.value.type === 'Call' && stmt.value.callee === 'print') {
        const args = stmt.value.args.map(exprToString).join(', ');
        return `${pad}println!("{}", ${args});\n`;
      }
      return `${pad}${exprToString(stmt.value)};\n`;
    }
    case 'If': {
      let res = `${pad}if ${exprToString(stmt.condition)} {\n`;
      for (const s of stmt.thenBranch) res += emitRustStmt(s, indent + 1);
      res += `${pad}}`;
      if (stmt.elseBranch) {
        res += ` else {\n`;
        for (const s of stmt.elseBranch) res += emitRustStmt(s, indent + 1);
        res += `${pad}}`;
      }
      return res + '\n';
    }
    case 'While': {
      let res = `${pad}while ${exprToString(stmt.condition)} {\n`;
      for (const s of stmt.body) res += emitRustStmt(s, indent + 1);
      res += `${pad}}\n`;
      return res;
    }
    default:
      return '';
  }
}

