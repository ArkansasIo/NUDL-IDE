import { Program, Stmt, Expr, FunctionDecl, TargetLanguage } from './types';

export interface CodegenResult {
  code: string;
  target: TargetLanguage;
  filename: string;
  syntaxLanguage: string;
}

export function generateCode(program: Program, target: TargetLanguage): CodegenResult {
  switch (target) {
    case 'C++':
      return {
        code: generateCpp(program),
        target,
        filename: 'main.cpp',
        syntaxLanguage: 'cpp',
      };
    case 'C':
      return {
        code: generateC(program),
        target,
        filename: 'main.c',
        syntaxLanguage: 'c',
      };
    case 'Rust':
      return {
        code: generateRust(program),
        target,
        filename: 'main.rs',
        syntaxLanguage: 'rust',
      };
    case 'Python':
      return {
        code: generatePython(program),
        target,
        filename: 'main.py',
        syntaxLanguage: 'python',
      };
    case 'JavaScript':
      return {
        code: generateJavaScript(program),
        target,
        filename: 'main.js',
        syntaxLanguage: 'javascript',
      };
    case 'TypeScript':
      return {
        code: generateTypeScript(program),
        target,
        filename: 'main.ts',
        syntaxLanguage: 'typescript',
      };
    case 'C#':
      return {
        code: generateCSharp(program),
        target,
        filename: 'Program.cs',
        syntaxLanguage: 'csharp',
      };
    case 'Java':
      return {
        code: generateJava(program),
        target,
        filename: 'Main.java',
        syntaxLanguage: 'java',
      };
    case 'Swift':
      return {
        code: generateSwift(program),
        target,
        filename: 'main.swift',
        syntaxLanguage: 'swift',
      };
    case 'WASM':
      return {
        code: generateWat(program),
        target,
        filename: 'main.wat',
        syntaxLanguage: 'wasm',
      };
    case 'Interpreter':
    default:
      return {
        code: '// Target: Noodle Interpreter\n// Direct runtime evaluation active.\n',
        target: 'Interpreter',
        filename: 'main.nudl',
        syntaxLanguage: 'plaintext',
      };
  }
}

// -------------------------------------------------------------
// Helper expression formatters
// -------------------------------------------------------------

function exprToString(e: Expr): string {
  switch (e.type) {
    case 'Literal':
      if (e.kind === 'String') return JSON.stringify(e.value);
      if (e.kind === 'Null') return 'null';
      return e.value;
    case 'Name':
      return e.value;
    case 'Unary':
      return `(${e.op}${exprToString(e.rhs)})`;
    case 'Binary':
      return `(${exprToString(e.lhs)} ${e.op} ${exprToString(e.rhs)})`;
    case 'Call': {
      const args = e.args.map(exprToString).join(', ');
      return `${e.callee}(${args})`;
    }
    case 'Array':
      return `[${e.elements.map(exprToString).join(', ')}]`;
    case 'Member':
      return `${exprToString(e.object)}.${e.property}`;
    case 'Index':
      return `${exprToString(e.object)}[${exprToString(e.index)}]`;
    case 'StructInst': {
      const fields = e.fields.map((f) => `${f.name}: ${exprToString(f.value)}`).join(', ');
      return `{ ${fields} }`;
    }
    default:
      return 'null';
  }
}

// -------------------------------------------------------------
// C++23 Generator (matching 03-compiler/src/codegen.cpp)
// -------------------------------------------------------------
function generateCpp(program: Program): string {
  let out = '// Generated by NUDL 0.3 C++ Backend\n#include <iostream>\n#include <string>\n#include <vector>\n\n';

  // Structs
  for (const s of program.structs) {
    out += `struct ${s.name} {\n`;
    for (const f of s.fields) {
      out += `    ${mapCppType(f.type)} ${f.name};\n`;
    }
    out += `};\n\n`;
  }

  // Functions
  for (const f of program.functions) {
    const isMain = f.name === 'main';
    const retType = isMain ? 'int' : mapCppType(f.returnType);
    const params = f.params.map((p) => `${mapCppType(p.type)} ${p.name}`).join(', ');
    out += `${retType} ${f.name}(${params}) {\n`;
    for (const stmt of f.body) {
      out += emitCppStmt(stmt, 1);
    }
    if (isMain && !f.body.some((s) => s.type === 'Return')) {
      out += `    return 0;\n`;
    }
    out += `}\n\n`;
  }

  // If no main function, synthesize one for top-level statements
  if (!program.functions.some((f) => f.name === 'main')) {
    out += `int main() {\n`;
    for (const stmt of program.statements) {
      if (stmt.type !== 'StructDecl' && stmt.type !== 'SchemaDecl' && stmt.type !== 'DataDecl') {
        out += emitCppStmt(stmt, 1);
      }
    }
    out += `    return 0;\n}\n`;
  }

  return out;
}

function mapCppType(t: string): string {
  switch (t) {
    case 'i64':
    case 'int':
    case 'integer':
    case 'u64':
      return 'long long';
    case 'f64':
    case 'float':
    case 'double':
      return 'double';
    case 'bool':
      return 'bool';
    case 'string':
    case 'text':
      return 'std::string';
    case 'void':
      return 'void';
    default:
      if (t.endsWith('[]')) {
        return `std::vector<${mapCppType(t.slice(0, -2))}>`;
      }
      return t || 'auto';
  }
}

function emitCppStmt(stmt: Stmt, indent: number): string {
  const pad = '    '.repeat(indent);
  switch (stmt.type) {
    case 'Binding':
      return `${pad}${stmt.constant ? 'const auto' : 'auto'} ${stmt.name} = ${exprToString(stmt.value)};\n`;
    case 'Assign':
      return `${pad}${stmt.target} = ${exprToString(stmt.value)};\n`;
    case 'Return':
      return `${pad}return ${exprToString(stmt.value)};\n`;
    case 'ExprStmt': {
      if (stmt.value.type === 'Call' && stmt.value.callee === 'print') {
        const arg = stmt.value.args.map(exprToString).join(' << " " << ');
        return `${pad}std::cout << ${arg} << std::endl;\n`;
      }
      return `${pad}${exprToString(stmt.value)};\n`;
    }
    case 'If': {
      let res = `${pad}if (${exprToString(stmt.condition)}) {\n`;
      for (const s of stmt.thenBranch) res += emitCppStmt(s, indent + 1);
      res += `${pad}}`;
      if (stmt.elseBranch) {
        res += ` else {\n`;
        for (const s of stmt.elseBranch) res += emitCppStmt(s, indent + 1);
        res += `${pad}}`;
      }
      return res + '\n';
    }
    case 'While': {
      let res = `${pad}while (${exprToString(stmt.condition)}) {\n`;
      for (const s of stmt.body) res += emitCppStmt(s, indent + 1);
      res += `${pad}}\n`;
      return res;
    }
    default:
      return '';
  }
}

