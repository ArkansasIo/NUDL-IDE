// Swift Generator
// -------------------------------------------------------------
function generateSwift(program: Program): string {
  let out = '// Generated by NUDL 0.3 Swift Backend\nimport Foundation\n\n';

  for (const f of program.functions) {
    const isMain = f.name === 'main';
    if (!isMain) {
      const params = f.params.map((p) => `${p.name}: ${p.type}`).join(', ');
      out += `func ${f.name}(${params}) -> ${f.returnType} {\n`;
      for (const stmt of f.body) {
        out += emitSwiftStmt(stmt, 1);
      }
      out += `}\n\n`;
    } else {
      for (const stmt of f.body) {
        out += emitSwiftStmt(stmt, 0);
      }
    }
  }

  return out;
}

function emitSwiftStmt(stmt: Stmt, indent: number): string {
  const pad = '    '.repeat(indent);
  switch (stmt.type) {
    case 'Binding':
      return `${pad}${stmt.constant ? 'let' : 'var'} ${stmt.name} = ${exprToString(stmt.value)}\n`;
    case 'ExprStmt':
      return `${pad}${exprToString(stmt.value)}\n`;
    case 'Return':
      return `${pad}return ${exprToString(stmt.value)}\n`;
    default:
      return '';
  }
}

