import assert from "node:assert/strict";
import test from "node:test";
import { analyzeRequest, generateRequest, lexRequest, parseRequestApi, runRequest } from "../android-api/src/nudlApi";

test("Android API lex endpoint adapter", () => {
  const response = lexRequest({ source: "let x = 42;" });
  assert.equal(response.ok, true);
  assert.ok(response.result);
});

test("Android API parse endpoint adapter", () => {
  const response = parseRequestApi({ source: "fn main() { print(\"hello\"); }" });
  assert.equal(response.ok, true);
  assert.ok(response.result);
});

test("Android API analyzer reports invalid source", () => {
  const response = analyzeRequest({ source: "fn main( {" });
  assert.equal(response.ok, false);
  assert.ok(response.diagnostics.length > 0);
});

test("Android API interpreter executes NUDL", () => {
  const response = runRequest({ source: "fn main() { let x = 2 + 3; print(x); return x; }" });
  assert.equal(response.ok, true);
  const result = response.result as { output: string[]; returnValue: number };
  assert.deepEqual(result.output, ["5"]);
  assert.equal(result.returnValue, 5);
});

test("Android API generator emits TypeScript", () => {
  const response = generateRequest({
    source: "fn main() { print(\"hello\"); }",
    target: "TypeScript",
  });
  assert.equal(response.ok, true);
  const result = response.result as { code: string; target: string; filename: string };
  assert.equal(result.target, "TypeScript");
  assert.equal(result.filename, "main.ts");
  assert.match(result.code, /Generated by NUDL 0\.3/);
});
